"""A project's own docs/sdlc/STATE.md must never be overwritten; the generated view goes to AF_STATE.md."""
import subprocess
import unittest

import afhelpers as H
from afhelpers import core

NL = chr(10)
FOREIGN = (NL.join(["# Project state (hand written)", "", "Important notes the team maintains by hand."] +
                   ["line %d" % i for i in range(200)]) + NL).encode("utf-8")
MARK = "Generated by tools/af_cli.py"


def state_md(repo):
    return H.sdlc(repo) / "STATE.md"


def af_state_md(repo):
    return H.sdlc(repo) / "AF_STATE.md"


class StateView(unittest.TestCase):
    def setUp(self):
        self.repo = H.make_repo(self)

    def commit_foreign(self):
        state_md(self.repo).parent.mkdir(parents=True, exist_ok=True)
        state_md(self.repo).write_bytes(FOREIGN)
        H.git(self.repo, "add", "docs/sdlc/STATE.md")
        H.git(self.repo, "commit", "-q", "-m", "add hand-written state")

    def assert_foreign_intact(self):
        self.assertEqual(state_md(self.repo).read_bytes(), FOREIGN)
        r = subprocess.run(["git", "-C", str(self.repo), "diff", "--quiet", "--", "docs/sdlc/STATE.md"])
        self.assertEqual(r.returncode, 0, "tracked STATE.md shows a diff")

    def test_foreign_tracked_state_survives_every_writer_command(self):
        self.commit_foreign()
        steps = [("start", "S"), ("pause",), ("resume",), ("mode", "soft"), ("mode", "hard"), ("off",), ("on",)]
        for args in steps:
            with self.subTest(cmd=args):
                r = H.run_cli(self.repo, *args)
                self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
                self.assert_foreign_intact()
        H.write_artifact(self.repo, "requirements.md", "req")
        r = H.run_cli(self.repo, "next")
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertEqual(core.read_state(self.repo)["phase"], 2)
        self.assert_foreign_intact()

    def test_generated_view_goes_to_af_state_with_current_content(self):
        self.commit_foreign()
        H.run_cli(self.repo, "start", "Viewed")
        H.write_artifact(self.repo, "requirements.md", "req")
        H.run_cli(self.repo, "next")
        self.assertTrue((H.sdlc(self.repo) / "state.json").is_file())
        text = af_state_md(self.repo).read_text(encoding="utf-8")
        self.assertIn(MARK, text)
        self.assertIn("Sprint: Viewed", text)
        self.assertIn("Phase: 2 Backlog", text)
        self.assertEqual(text, core.render_state_md(self.repo, core.read_state(self.repo)))
        self.assert_foreign_intact()

    def test_migrate_on_legacy_state_keeps_foreign_state_md(self):
        self.commit_foreign()
        H.set_state(self.repo, phase=1, sid=None)
        self.assert_foreign_intact()  # the helper's write_state already went to AF_STATE.md
        r = H.run_cli(self.repo, "migrate")
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertIn("sprint_id", (H.sdlc(self.repo) / "state.json").read_text(encoding="utf-8"))
        self.assert_foreign_intact()
        self.assertTrue(af_state_md(self.repo).is_file())

    def test_uncommitted_foreign_state_md_is_also_protected(self):
        state_md(self.repo).parent.mkdir(parents=True, exist_ok=True)
        state_md(self.repo).write_bytes(FOREIGN)  # untracked
        H.run_cli(self.repo, "start", "S")
        self.assertEqual(state_md(self.repo).read_bytes(), FOREIGN)
        self.assertTrue(af_state_md(self.repo).is_file())

    def test_no_state_md_means_state_md_is_created(self):
        r = H.run_cli(self.repo, "start", "S")
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertTrue(state_md(self.repo).is_file())
        self.assertIn(MARK, state_md(self.repo).read_text(encoding="utf-8"))
        self.assertFalse(af_state_md(self.repo).exists())

    def test_existing_generated_state_md_keeps_being_refreshed(self):
        H.run_cli(self.repo, "start", "S")
        first = state_md(self.repo).read_text(encoding="utf-8")
        H.write_artifact(self.repo, "requirements.md", "req")
        H.run_cli(self.repo, "next")
        second = state_md(self.repo).read_text(encoding="utf-8")
        self.assertNotEqual(first, second)
        self.assertIn("Phase: 2 Backlog", second)
        self.assertFalse(af_state_md(self.repo).exists(), "a generated STATE.md must not be redirected")

    def test_foreign_file_restored_over_generated_one_redirects_later_writes(self):
        H.run_cli(self.repo, "start", "S")
        self.assertIn(MARK, state_md(self.repo).read_text(encoding="utf-8"))
        state_md(self.repo).write_bytes(FOREIGN)  # operator puts their own file back
        H.write_artifact(self.repo, "requirements.md", "req")
        r = H.run_cli(self.repo, "next")
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertEqual(state_md(self.repo).read_bytes(), FOREIGN)
        self.assertIn("Phase: 2 Backlog", af_state_md(self.repo).read_text(encoding="utf-8"))

    def test_state_view_name_unit(self):
        d = H.sdlc(self.repo)
        d.mkdir(parents=True)
        self.assertEqual(core.state_view_name(d), "STATE.md")  # absent
        (d / "STATE.md").write_text("# SDLC state" + NL + NL + MARK + " from state.json" + NL, encoding="utf-8")
        self.assertEqual(core.state_view_name(d), "STATE.md")  # ours
        (d / "STATE.md").write_text("x" * 700 + MARK, encoding="utf-8")
        self.assertEqual(core.state_view_name(d), "AF_STATE.md")  # mark beyond the first 600 chars is not ours
        (d / "STATE.md").write_bytes(b"")
        self.assertEqual(core.state_view_name(d), "AF_STATE.md")  # empty file is not ours


if __name__ == "__main__":
    unittest.main()
