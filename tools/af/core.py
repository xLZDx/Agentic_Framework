"""Shared helpers: framework root, phase map, git, per-project SDLC state."""
from __future__ import annotations

import glob
import json
import os
import subprocess
from datetime import datetime, timezone
from pathlib import Path

FRAMEWORK_ROOT = Path(__file__).resolve().parents[2]
PHASE_MAP_PATH = FRAMEWORK_ROOT / "core" / "orchestration" / "phase-map.json"


def load_phase_map() -> dict:
    return json.loads(PHASE_MAP_PATH.read_text(encoding="utf-8"))


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def git(project: Path, *args: str) -> str:
    out = subprocess.run(
        ["git", "-C", str(project), *args],
        capture_output=True, text=True, encoding="utf-8", errors="replace", check=False,
    )
    if out.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {out.stderr.strip()}")
    return out.stdout


def git_root(path: Path) -> Path:
    return Path(git(path, "rev-parse", "--show-toplevel").strip())


def head(project: Path) -> str:
    return git(project, "rev-parse", "HEAD").strip()


def tracked_dirty(project: Path) -> list[str]:
    """Tracked modifications and staged changes; untracked files do not count."""
    lines = git(project, "status", "--porcelain", "--untracked-files=no").splitlines()
    return [ln for ln in lines if ln.strip()]


def state_dir(project: Path) -> Path:
    return project / load_phase_map()["state_dir"]


def phase_def(n: int) -> dict:
    for p in load_phase_map()["phases"]:
        if p["n"] == n:
            return p
    raise KeyError(f"unknown phase {n}")


def read_state(project: Path) -> dict | None:
    f = state_dir(project) / "state.json"
    if not f.is_file():
        return None
    return json.loads(f.read_text(encoding="utf-8"))


def write_state(project: Path, state: dict) -> None:
    d = state_dir(project)
    d.mkdir(parents=True, exist_ok=True)
    state["updated"] = now_iso()
    (d / "state.json").write_text(json.dumps(state, indent=2) + "\n", encoding="utf-8")
    (d / "STATE.md").write_text(render_state_md(project, state), encoding="utf-8")


def artifact_present(project: Path, pattern: str, since: float | None = None) -> bool:
    """An artifact counts only if it exists and (when `since` is given) was written after the sprint started."""
    for f in glob.glob(str(state_dir(project) / pattern)):
        if since is None or os.path.getmtime(f) >= since:
            return True
    return False


def missing_artifacts(project: Path, n: int) -> list[str]:
    st = read_state(project) or {}
    since = st.get("started_epoch")
    return [a for a in phase_def(n)["artifacts"] if not artifact_present(project, a, since)]


def new_sprint_state(project: Path, title: str, mode: str) -> dict:
    """Initial state; remembers the start time and HEAD so stale artifacts and narrowed review bases are rejected."""
    try:
        start_head = head(project)
    except Exception:
        start_head = None
    return {"title": title, "phase": 1, "mode": mode, "paused": False, "history": [],
            "started_epoch": datetime.now(timezone.utc).timestamp(), "start_head": start_head}


def render_state_md(project: Path, state: dict) -> str:
    n = state["phase"]
    try:
        h = head(project)[:12]
    except Exception:
        h = "n/a"
    rows = ["| # | Phase | Artifacts | Status |", "|---|---|---|---|"]
    for p in load_phase_map()["phases"]:
        miss = missing_artifacts(project, p["n"])
        status = "current" if p["n"] == n else ("done" if p["n"] < n else "pending")
        rows.append(f"| {p['n']} | {p['name']} | {', '.join(p['artifacts'])} | {status}{' (missing: ' + ', '.join(miss) + ')' if miss and p['n'] <= n else ''} |")
    return (
        "# SDLC state\n\n"
        "Generated by tools/af_cli.py from state.json. Do not edit by hand.\n\n"
        f"Sprint: {state.get('title', '')}   Phase: {n} {phase_def(n)['name']}   Mode: {state.get('mode', 'hard')}   HEAD: {h}   Updated: {state['updated']}\n\n"
        + "\n".join(rows) + "\n"
    )


def find_review_js() -> Path | None:
    cfg = load_phase_map()["pm_review"]
    env = os.environ.get(cfg["env_override"])
    cands = [env] if env else []
    cands += cfg["review_js_candidates"]
    for c in cands:
        if c and Path(c).is_file():
            return Path(c)
    return None
